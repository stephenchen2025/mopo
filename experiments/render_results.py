#!/usr/bin/env python3
"""Render the synthetic experiment JSON into results/RESULTS.md.

Kept separate from the runner so the write-up can be regenerated without re-running the
experiments, and so the numbers in the markdown are always mechanically derived from the
JSON rather than retyped.
"""

from __future__ import annotations

import argparse
import json
import pathlib


def fmt(stats: dict, key: str = "hypervolume") -> str:
    return f"{stats[key]:.4f} ± {stats[key + '_std']:.4f}"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", default="results/synthetic_results.json")
    parser.add_argument("--output", default="results/RESULTS.md")
    args = parser.parse_args()

    data = json.loads(pathlib.Path(args.input).read_text())
    cfg = data["config"]
    out: list[str] = []
    add = out.append

    add("# PaCE — synthetic validation results\n")
    add("Generated by `experiments/render_results.py` from `synthetic_results.json`. ")
    add("Do not edit by hand.\n")
    add(
        f"**Setup.** {cfg['seeds']} seeds per cell, {cfg['steps']} steps, "
        f"{data['rollouts_per_run']:,} rollouts per run — identical budget for every "
        f"method, including the multi-model baseline. lr={cfg['lr']}, "
        f"entropy={cfg['entropy']}, {cfg['contexts']} contexts, "
        f"reward noise {cfg['noise']}. Hypervolume is measured against a shared reference "
        f"point with greedy decoding; `±` is the standard deviation across seeds.\n"
    )
    add(
        "**What this validates.** The optimizer's frontier behaviour on a synthetic "
        "multi-objective bandit. It says nothing about language models — no LLM has been "
        "trained with this.\n"
    )

    # ---- main -------------------------------------------------------------------
    if "main" in data:
        add("\n## 1. Main comparison\n")
        add(
            "The front's curvature is a knob in this environment, which is the point: "
            "linear scalarization is *provably* unable to reach the interior of a concave "
            "front, and perfectly adequate on a convex one. Both cases are measured.\n"
        )
        for label in ("concave", "convex"):
            if label not in data["main"]:
                continue
            block = data["main"][label]
            oracle = block["oracle_hypervolume"]
            add(f"\n### {label.capitalize()} front (oracle HV = {oracle:.4f})\n")
            add("| method | hypervolume | % of oracle | controllability | models |")
            add("|---|---|---|---|---|")
            ranked = sorted(block["methods"].items(), key=lambda kv: -kv[1]["hypervolume"])
            for name, stats in ranked:
                add(
                    f"| `{name}` | {fmt(stats)} | {stats['pct_of_oracle']:.1f}% "
                    f"| {stats['controllability_mean']:+.3f} "
                    f"| {stats['n_models']:.0f} |"
                )

    # ---- ablation ---------------------------------------------------------------
    if "ablation" in data:
        block = data["ablation"]
        add(f"\n## 2. Ablations (concave front, oracle HV = " f"{block['oracle_hypervolume']:.4f})\n")
        add("Each row changes one setting of the full method.\n")
        add("| variant | hypervolume | % of oracle |")
        add("|---|---|---|")
        for name, stats in block["variants"].items():
            add(f"| {name} | {fmt(stats)} | {stats['pct_of_oracle']:.1f}% |")

    # ---- scale invariance -------------------------------------------------------
    if "scale_invariance" in data:
        add("\n## 3. Scale invariance\n")
        add(
            "A strictly increasing transform is applied to one objective before the "
            "learner sees it. This does not move the Pareto set by a single point, so any "
            "change in a method's result is pure sensitivity to reward scale.\n"
        )
        blocks = data["scale_invariance"]
        methods = sorted({m for b in blocks.values() for m in b["methods"]})
        add("| transform | " + " | ".join(f"`{m}`" for m in methods) + " |")
        add("|---" * (len(methods) + 1) + "|")
        for tag, block in blocks.items():
            cells = [fmt(block["methods"][m]) if m in block["methods"] else "—" for m in methods]
            add(f"| {tag} | " + " | ".join(cells) + " |")

    # ---- bandit -----------------------------------------------------------------
    if "bandit" in data:
        add("\n## 4. Coverage bandit\n")
        add(
            "The bandit can only pay off when there is something to reallocate: frontier "
            "regions of genuinely uneven difficulty, *and* a direction grid larger than "
            "the group size. With `D` close to `K` and sampling without replacement, a "
            "group covers nearly the whole grid whatever the bandit prefers, so the "
            "mechanism is inert by construction.\n"
        )
        add("| condition | grid | coverage bandit | uniform sampling |")
        add("|---|---|---|---|")
        for label, block in data["bandit"].items():
            for grid, cell in block["grids"].items():
                add(f"| {label} | {grid} | {fmt(cell['pace'])} " f"| {fmt(cell['pace_uniform'])} |")

    # ---- interpretation ---------------------------------------------------------
    if "main" in data and "ablation" in data:
        seeds = cfg["seeds"]
        conc = data["main"]["concave"]["methods"]
        conv = data["main"]["convex"]["methods"]
        abl = data["ablation"]["variants"]
        add("\n## Reading these numbers\n")
        add(
            f"Standard errors are `std / sqrt({seeds})`, so a gap of roughly "
            f"{2 * 0.07 / seeds**0.5:.3f} hypervolume is about two standard errors. "
            "Several gaps below are smaller than that and are called out as such.\n"
        )

        add(
            "\n**1. The headline, with its condition attached.** On the concave front, at "
            f"identical rollout budget, `pace` reaches "
            f"{conc['pace']['pct_of_oracle']:.0f}% of oracle with **one** model while "
            f"`fixed_scalar` — the status quo of N independent fixed-weight runs — reaches "
            f"{conc['fixed_scalar']['pct_of_oracle']:.0f}% with **nine**. That is the "
            "result the method was built for.\n"
        )
        add(
            f"\nOn the convex front the ordering reverses: `fixed_scalar` reaches "
            f"{conv['fixed_scalar']['pct_of_oracle']:.0f}% and `pace` "
            f"{conv['pace']['pct_of_oracle']:.0f}%. This is not a wash to be explained "
            "away — when the front is convex, weighted sums are the right tool and PaCE's "
            "machinery is overhead. **PaCE's advantage is conditional on front geometry, "
            "and it costs something when the geometry is benign.** If you know your "
            "objectives trade off smoothly, use the simple thing.\n"
        )

        si = data.get("scale_invariance", {})
        if si:
            ident = si["identity"]["methods"]
            exp4 = si["obj1 -> exp(4x)"]["methods"]
            add(
                "\n**2. Scale invariance is the most robust result here.** Applying "
                "`exp(4x)` to one objective does not move the Pareto set by a single "
                "point. `pace_uniform` is unmoved by it "
                f"({ident['pace_uniform']['hypervolume']:.4f} -> "
                f"{exp4['pace_uniform']['hypervolume']:.4f}, identical). `cond_linear` "
                f"collapses from {ident['cond_linear']['hypervolume']:.4f} to "
                f"{exp4['cond_linear']['hypervolume']:.4f} — and note the ± of "
                f"{exp4['cond_linear']['hypervolume_std']:.4f}: every seed fails the same "
                "way, so this is a deterministic structural failure, not bad luck. "
                "MO-GRPO-style per-objective z-scoring "
                f"({ident['cond_mognorm']['hypervolume']:.4f} -> "
                f"{exp4['cond_mognorm']['hypervolume']:.4f}) survives much better than a "
                "raw weighted sum, as its authors intend, but is still not invariant — a "
                "z-score is only affine-invariant, and this transform is not affine.\n"
            )

        add(
            "\n**3. Frontier shaping is the component with the clearest evidence.** "
            f"Removing it (`lambda_front=0.0`) costs "
            f"{abl['full']['pct_of_oracle'] - abl['lambda_front=0.0']['pct_of_oracle']:.1f} "
            f"points of oracle ({abl['lambda_front=0.0']['pct_of_oracle']:.1f}% vs "
            f"{abl['full']['pct_of_oracle']:.1f}%), several standard errors. Removing just "
            f"the crowding half costs "
            f"{abl['full']['pct_of_oracle'] - abl['lambda_crowd=0.0']['pct_of_oracle']:.1f} "
            "points. Doubling it to 0.6 changes nothing, so the setting is not delicate.\n"
        )

        add(
            "\n**4. Two mechanisms are *not* established by this experiment, and saying "
            "so is more useful than a hedge.**\n"
        )
        add(
            f"\n- *The cross-direction leave-one-out baseline.* Collapsing it to a "
            f"constant baseline (`loo_shrinkage=1.0`) costs only "
            f"{abl['full']['pct_of_oracle'] - abl['loo_shrinkage=1.0']['pct_of_oracle']:.1f} "
            "points, within noise. That is not evidence against it so much as evidence "
            "that this environment cannot test it: the action space is tiny and the "
            "gradient variance is already low, which is precisely where a "
            "variance-reduction device has the least to offer. It needs a setting with "
            "expensive, high-variance rollouts — an LLM — to be worth anything or to be "
            "shown worthless."
        )
        add(
            "- *The coverage bandit.* Its effects are consistently within one standard "
            "error. The direction is at least consistent with the mechanism: it helps at "
            "`D=41` and not at `D=9`, matching the prediction that a group sampling "
            "8 of 9 grid directions without replacement covers the grid regardless of what "
            "the bandit prefers. But 'directionally consistent and inside the noise' is "
            "not a result.\n"
        )

        add(
            f"\n**5. Controllability catches a failure every other metric misses.** "
            f"`cond_dominance` posts a competitive "
            f"{conc['cond_dominance']['pct_of_oracle']:.1f}% hypervolume on the concave "
            f"front — near the top of the table — with a controllability of "
            f"{conc['cond_dominance']['controllability_mean']:+.3f}. Its preference knob "
            "does essentially nothing. A Pareto-rank-only advantage is direction-agnostic "
            "by construction, so the policy has no reason to learn what `w` means; it "
            "finds a good frontier and refuses to be steered along it. Judged on "
            "hypervolume alone it would look like one of the better methods here.\n"
        )

        add("\n### Caveats\n")
        add(
            "- One synthetic environment with a linear policy over ~21 actions. The policy "
            "class is provably expressive enough to cover the front, so failures are "
            "attributable to the objective rather than to capacity — but that is a long "
            "way from a language model."
        )
        add(
            "- Hyperparameters (lr, entropy, grid resolution) were selected by sweeping "
            "`pace_uniform`, then applied unchanged to every method. That is a mild "
            "advantage to PaCE and the reader should discount accordingly."
        )
        add(
            "- Absolute numbers sit near 60% of oracle; none of these runs is trained to "
            "convergence, and the seed-to-seed spread is wide."
        )
        add("- **No language model has been trained with this.** Nothing here transfers " "automatically.\n")

    add("\n## Method key\n")
    for name, desc in data["method_descriptions"].items():
        add(f"- `{name}` — {desc}")

    path = pathlib.Path(args.output)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(out) + "\n")
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
